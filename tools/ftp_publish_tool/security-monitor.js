const EXECUTABLE_EXTENSIONS = new Set([
  ".php", ".php3", ".php4", ".php5", ".php7", ".php8", ".phtml", ".pht", ".phar", ".inc",
  ".asp", ".aspx", ".ashx", ".jsp", ".jspx", ".cgi", ".pl", ".py", ".sh",
]);

const TEXT_EXTENSIONS = new Set([
  ...EXECUTABLE_EXTENSIONS,
  ".htm", ".html", ".shtml", ".js", ".mjs", ".cjs", ".css", ".json", ".xml", ".txt",
  ".ini", ".conf", ".config", ".yml", ".yaml", ".md",
]);

const UPLOAD_LIKE_SEGMENTS = new Set([
  "upload", "uploads", "uploaded", "files", "images", "image", "img", "media", "assets", "static",
  "tmp", "temp",
]);

const SKIP_DIRECTORIES = new Set([".", "..", ".git", ".svn", "node_modules"]);

